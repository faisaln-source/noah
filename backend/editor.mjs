import path from 'node:path';
import { promises as fs } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { DATA, required, all, remove } from './store.mjs';
import { run, update, checkCancelled } from './jobs.mjs';
import { pythonProcess } from './media.mjs';
import { PRESETS, validateTimeline, render } from './render.mjs';
import { retimeCaptions, serializeCaptions, suppliedCaptions } from './subtitles.mjs';

async function timelineSpeech(clips, payload, job, intro = 0, speed = 1) {
  const segments = [];
  let offset = intro;
  for (const [index, clip] of clips.entries()) {
    checkCancelled(job);
    if (clip.type === 'title') { offset += clip.duration || 2; continue; }
    const source = required('media', clip.sourceId);
    update(job, { stage: `Understanding speech in selected range ${index + 1} of ${clips.length}`, progress: index / clips.length * 90 });
    let transcript = source.transcript;
    if (payload.forceWordTiming && !(transcript?.segments?.length && transcript.segments.every(line => line.words?.length))) transcript = undefined;
    if (!transcript && source.hasAudio !== false && payload.autoCaptions !== false) {
      const wave = path.join(DATA, 'work', `${job.id}-${index}.wav`);
      try {
        await run('ffmpeg', ['-y', '-v', 'error', '-ss', String(clip.start), '-i', path.join(DATA, source.file), '-t', String(clip.end - clip.start), '-vn', '-ac', '1', '-ar', '16000', wave], job);
        transcript = await pythonProcess({ operation: 'transcribe', file: wave, duration: clip.end - clip.start, model: 'base' }, job);
        segments.push(...retimeCaptions(transcript.segments || [], 0, clip.end - clip.start, offset, speed));
      } finally { await fs.unlink(wave).catch(() => {}); }
    } else if (transcript) segments.push(...retimeCaptions(transcript.segments || [], clip.start, clip.end, offset, speed));
    offset += (clip.end - clip.start) / speed;
  }
  return segments;
}
export async function generateTimelineCaptions(payload, job) {
  const { clips } = validateTimeline(payload);
  const segments = await timelineSpeech(clips, payload, job, 0, Number(payload.speed || 1));
  return { subtitles: serializeCaptions(segments), captionSegments: segments, wordCount: segments.reduce((sum, line) => sum + (line.words?.length || 0), 0) };
}

export async function automaticEdit(payload, job) {
  const { clips: originalClips, options } = validateTimeline(payload);
  const clips = originalClips.filter(clip => !clip.autoGenerated);
  const footage = clips.filter(clip => clip.type !== 'title');
  if (!footage.length) throw new Error('Add a video range before automatic editing.');
  const speed = Number(payload.aiPace ?? options.speed ?? 1);
  const duration = clips.reduce((sum, clip) => sum + (clip.type === 'title' ? clip.duration || 2 : clip.end - clip.start), 0);
  const outputDuration = clips.reduce((sum, clip) => sum + (clip.type === 'title' ? clip.duration || 2 : (clip.end - clip.start) / speed), 0);
  let intro = payload.aiIntro ? !options.sourceCanvas && ['9:16', '3:4'].includes(options.ratio) ? Math.min(2, Math.max(0, 120 - outputDuration)) : 2 : 0;
  if (intro < .5) intro = 0;
  const segments = payload.aiCaptions === false ? [] : await timelineSpeech(clips, { ...payload, forceWordTiming: options.captionStyle === 'gta6' }, job, intro, speed);
  const heading = (segments[0]?.text || required('media', footage[0].sourceId).title || 'Gameplay highlights').trim().split(/\s+/).slice(0, 10).join(' ').slice(0, 90);
  const lines = [''];
  const lineWidth = ['9:16', '3:4'].includes(options.ratio) ? 22 : 40;
  for (const word of heading.split(' ')) {
    if (lines.at(-1).length + word.length > lineWidth && lines.at(-1)) lines.push('');
    lines[lines.length - 1] += (lines.at(-1) ? ' ' : '') + word;
  }
  const style = PRESETS[options.preset] || PRESETS.viral;
  const timeline = { ...payload, ...style, preset: options.preset || 'viral', speed, title: heading, overlay: heading.split(' ').slice(0, 7).join(' ').slice(0, 60),
    transition: clips.length > 1 ? 'fade' : 'none', captions: segments.length > 0, subtitles: serializeCaptions(segments), captionSegments: segments,
    // Crossfades change global caption timing; keep direct cuts with generated captions.
    clips: [...(intro >= .5 ? [{ id: randomUUID(), type: 'title', autoGenerated: true, text: lines.join('\n'), start: 0, end: intro, duration: intro }] : []), ...clips] };
  timeline.transition = 'none';
  if (payload.aiHeading === false) timeline.overlay = '';
  timeline.shake = payload.aiMotion === 'punchy';
  if (payload.aiMotion === 'gentle') { timeline.zoom = false; timeline.shake = false; }
  if (payload.aiColor === 'cinematic') { timeline.effect = 'cinematic'; timeline.saturation = .95; timeline.contrast = 1.05; }
  if (payload.aiColor === 'vibrant') { timeline.effect = 'vivid'; timeline.saturation = 1.08; timeline.contrast = 1.06; }
  timeline.removeSilence = payload.aiRemoveSilence === true;
  timeline.normalize = payload.aiNormalize !== false;
  if (options.captionStyle === 'gta6') Object.assign(timeline, { captionStyle: 'gta6', captionFont: 'Anton', captionColor: options.captionColor || '#ff70bd', captionHighlightColor: options.captionHighlightColor || '#ffd08a', captionAnimation: options.captionAnimation || 'word-pop' });
  validateTimeline(timeline);
  return { timeline, firstFootageIndex: timeline.clips.findIndex(clip => clip.type !== 'title'), footageSeconds: duration, titleSeconds: intro, notes: [`Kept all ${duration.toFixed(1)} seconds of selected footage${intro ? ` and added a ${intro}-second intro` : '; no intro card added'}.`, `Applied ${style.name}. ${segments.length} speech caption lines. All changes remain editable.`] };
}

export async function editorPreview(payload, job) {
  validateTimeline(payload);
  const speed = Number(payload.speed || 1);
  let available = payload.clips;
  let subtitles = payload.subtitles;
  let captionSegments = suppliedCaptions(payload);
  if (payload.previewSceneIndex !== undefined) {
    const index = Number(payload.previewSceneIndex);
    if (!Number.isInteger(index) || index < 0 || index >= available.length) throw new Error('Choose a valid preview scene.');
    const offset = available.slice(0, index).reduce((sum, clip) => sum + (clip.type === 'title' ? clip.duration || 2 : (clip.end - clip.start) / speed), 0);
    available = [available[index]];
    const length = available[0].type === 'title' ? available[0].duration || 2 : (available[0].end - available[0].start) / speed;
    if (subtitles) { captionSegments = retimeCaptions(captionSegments, offset, offset + (payload.previewDraft ? Math.min(30, length) : length), 0, 1); subtitles = serializeCaptions(captionSegments); }
  }
  let remaining = payload.previewDraft ? 30 : Infinity;
  const clips = [];
  for (const clip of available) {
    if (remaining <= .01) break;
    const duration = clip.type === 'title' ? Number(clip.duration || 2) : (clip.end - clip.start) / speed;
    const used = Math.min(duration, remaining);
    if (clip.type === 'title' && used < .5) break;
    clips.push(clip.type === 'title' ? { ...clip, duration: used } : { ...clip, end: clip.start + used * speed });
    remaining -= used;
  }
  const result = await render({ ...payload, subtitles, captionSegments, clips, ...(payload.previewDraft ? { sourceCanvas: false, resolution: 360, fps: 30, quality: 'high' } : { quality: 'lossless' }), encoder: 'cpu', bitrate: 0, preview: true, previewOutputResolution: payload.previewDraft ? payload.resolution || 1080 : 0 }, job);
  // Retain the three most recent previews belonging to this editor session.
  for (const previous of all('media').filter(item => item.kind === 'preview' && item.previewSession === payload.previewSession).slice(3)) {
    for (const name of [previous.file, previous.thumbnail, previous.srt, previous.vtt].filter(Boolean)) {
      if (path.basename(name) === name) await fs.unlink(path.join(DATA, name)).catch(() => {});
    }
    remove('media', previous.id);
  }
  return { ...result, fullQuality: !payload.previewDraft, note: payload.previewDraft ? 'Draft preview: first 30 seconds.' : 'Full-duration, lossless edited preview at the selected canvas and source frame rate. Download is the same file shown here.' };
}
